const fs = require('node:fs');
const path = require('node:path');
const model = fs.readFileSync(path.join(__dirname, 'model.js'), 'utf8');
const plugin = fs.readFileSync(path.join(__dirname, 'plugin.js'), 'utf8');
const rendering = fs.readFileSync(path.join(__dirname, 'rendering.js'), 'utf8');
const drag = fs.readFileSync(path.join(__dirname, 'drag.js'), 'utf8');
const sorting = fs.readFileSync(path.join(__dirname, 'sorting.js'), 'utf8');
const wrap = source => '(() => { const module = { exports: {} };\n' + source + '\nreturn module.exports; })()';
const bundled = plugin.replace("require('./model')", () => wrap(model)).replace("require('./rendering')", () => wrap(rendering)).replace("require('./drag')", () => wrap(drag)).replace("require('./sorting')", () => wrap(sorting));
fs.writeFileSync(path.join(__dirname, '..', 'main.js'), '// Generated by build.js. Edit plugin.js or model.js instead.\n' + bundled);
fs.copyFileSync(path.join(__dirname, '..', 'Template.md'),path.join(__dirname, '..', 'Example.md'));
